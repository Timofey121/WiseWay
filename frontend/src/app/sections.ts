// Разделы продуктовой оболочки WiseWay.
//
// Порядок и состав разделов фиксированы ТЗ §4: «Поиск», «Справочники»,
// «Очередь сортировки», «Карантин», «Журнал». Отдельной сводной панели
// (dashboard) нет, лишние разделы не добавляются.
//
// `id` — машинный идентификатор для состояния/тестов; `label` — русская
// пользовательская подпись. Значения `id` не показываются пользователю.

export type AppSectionId =
  | 'search'
  | 'dictionaries'
  | 'sorting'
  | 'quarantine'
  | 'audit'

export interface AppSection {
  /** Машинный идентификатор раздела (не отображается пользователю). */
  readonly id: AppSectionId
  /** Русская подпись раздела для навигации и заголовка. */
  readonly label: string
  /** Честное описание того, что появится в разделе позже. */
  readonly description: string
}

