// Общий in-memory реестр сброса приватного состояния вкладки.
//
// Модуль предоставляет единый механизм для очистки локального операционного
// состояния (например, поисковой выдачи, открытых списков, выбранных файлов)
// при logout, истечении сессии, блокировке пользователя или смене
// пользователя (AUTH-03, SRCH-18, FE §4).
//
// Реестр намеренно живёт только в памяти модуля: он не использует URL,
// history state, `localStorage`, `sessionStorage` и cookie. Он также не
// выполняет никаких сетевых запросов.
//
// Контракт:
// - `registerPrivateStateReset(reset)` регистрирует функцию сброса и
//   возвращает функцию отписки;
// - `resetPrivateState()` вызывает каждую зарегистрированную функцию ровно
//   один раз за вызов; сбой одной функции не мешает остальным.

export type PrivateStateReset = () => void

const registeredResets = new Set<PrivateStateReset>()

/**
 * Регистрирует сброс приватного состояния.
 *
 * @returns функция отписки: после её вызова `reset` больше не запускается.
 */
export function registerPrivateStateReset(
  reset: PrivateStateReset,
): () => void {
  registeredResets.add(reset)
  return () => {
    registeredResets.delete(reset)
  }
}

/**
 * Вызывает все зарегистрированные сбросы приватного состояния.
 *
 * Список фиксируется в начале вызова, поэтому каждая функция, зарегистрированная
 * на этот момент, вызывается ровно один раз. Функция, снятая с подписки до или
 * во время вызова, не запускается. Исключение внутри одного сброса подавляется,
 * чтобы остальные сбросы всё равно выполнились. Сетевые запросы не выполняются.
 */
export function resetPrivateState(): void {
  const snapshot = [...registeredResets]
  for (const reset of snapshot) {
    if (!registeredResets.has(reset)) {
      continue
    }
    try {
      reset()
    } catch {
      // Один сбойный сброс не должен блокировать очистку остального состояния.
    }
  }
}
